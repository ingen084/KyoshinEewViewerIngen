using System.Text;

namespace KyoshinEewViewer.CodeAnalysis.JmaXml;

/// <summary>
/// [JmaXmlType] の型の partial メンバーの実装と、値を保持するフィールドを出力する
/// </summary>
internal static class JmaXmlTypeEmitter
{
	private static string ValueType(string conv) => conv switch
	{
		"int" => "int",
		"float" => "float",
		"dt" => "global::System.DateTimeOffset",
		"ndt" => "global::System.DateTimeOffset?",
		_ => "string",
	};

	private static string Throw(string what) => "throw " + JmaXmlNames.Support + ".Missing(\"" + what + "\");";

	public static string Emit(TypeModel type)
	{
		var sb = new StringBuilder();
		sb.AppendLine("// <auto-generated/>");
		sb.AppendLine("#nullable enable");
		if (type.Namespace.Length > 0)
			sb.AppendLine("namespace " + type.Namespace + ";").AppendLine();
		sb.AppendLine("partial class " + type.Name + "<" + type.TypeParameter + ">");
		sb.AppendLine("{");
		sb.AppendLine("\t/// <summary>読み取りコードがこのオブジェクトに対して読み取るメンバーのビット</summary>");
		sb.AppendLine("\t" + JmaXmlNames.Hidden + "ulong __mask;");

		var flags = new HashSet<string>();
		foreach (var p in type.Props)
		{
			if (p.Error != null)
				continue;
			foreach (var container in p.Containers)
			{
				if (flags.Add(container.Flag))
					sb.AppendLine("\t" + JmaXmlNames.Hidden + "bool " + container.Flag + ";");
			}

			var absent = p.Kind == "list" ? "return default;" : "return null;";
			// 値がない場合の経路: 読み取り対象でなければ利用側の誤りとして例外にし、対象なら欠落として扱う
			var miss = "if ((__mask & " + p.Mask + ") == 0) throw " + JmaXmlNames.Support + ".NotSelected(\"" + type.Name + "." + p.Name + "\"); ";
			foreach (var container in p.Containers)
				miss += "if (!" + container.Flag + ") " + (container.Required ? Throw(container.Name + " ノード") : absent) + " ";

			switch (p.Kind)
			{
				case "text":
				case "attr":
				case "selftext":
				case "selfname":
					{
						var missing = p.Required ? Throw(p.Kind == "attr" ? p.Attr + " 属性" : (p.Elem ?? p.Name) + " ノード") : absent;
						string body;
						if (p.Conv == "str" || p.Kind == "selfname")
						{
							sb.AppendLine("\t" + JmaXmlNames.Hidden + "string? " + p.Field + ";");
							body = "var v = " + p.Field + "; if (v != null) return v; ";
						}
						else
						{
							sb.AppendLine("\t" + JmaXmlNames.Hidden + ValueType(p.Conv) + " " + p.Field + ";");
							sb.AppendLine("\t" + JmaXmlNames.Hidden + "bool " + p.HasField + ";");
							if (p.IsMethod)
							{
								sb.AppendLine("\tpublic partial bool " + p.Name + "(out " + p.CsType + " value) { " + miss + "value = " + p.Field + "; return " + p.HasField + "; }");
								break;
							}
							body = "if (" + p.HasField + ") return " + p.Field + "; ";
						}
						sb.AppendLine("\tpublic partial " + p.CsType + " " + p.Name + " { get { " + body + miss + missing + " } }");
						break;
					}
				case "obj":
					sb.AppendLine("\t" + JmaXmlNames.Hidden + "global::" + p.TypeKey + "<" + type.TypeParameter + ">? " + p.Field + ";");
					sb.AppendLine("\tpublic partial " + p.CsType + " " + p.Name + " { get { var v = " + p.Field + "; if (v != null) return v; " + miss + (p.Required ? Throw(p.Elem + " ノード") : absent) + " } }");
					break;
				case "list":
					{
						var element = "global::" + p.TypeKey + "<" + type.TypeParameter + ">";
						sb.AppendLine("\t" + JmaXmlNames.Hidden + JmaXmlNames.List + "<" + element + ">? " + p.Field + ";");
						var body = "";
						if (p.ItemChild != null && p.Required)
						{
							sb.AppendLine("\t" + JmaXmlNames.Hidden + "bool " + p.MissingItemField + ";");
							body = "if (" + p.MissingItemField + ") " + Throw(p.ItemChild + " ノード") + " ";
						}
						sb.AppendLine("\tpublic partial " + p.CsType + " " + p.Name + " { get { " + body + "var v = " + p.Field + "; if (v != null) return new(v); " + miss + "return default; } }");
						break;
					}
			}
		}
		sb.AppendLine("}");
		return sb.ToString();
	}
}
