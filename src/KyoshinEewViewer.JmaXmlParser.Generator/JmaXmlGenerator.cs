using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using System.Runtime.CompilerServices;

namespace KyoshinEewViewer.JmaXmlParser.Generator;

/// <summary>
/// [JmaXmlType] を付けた型の partial メンバーの実装と、[JmaXmlView] を付けた読み取りの単位ごとの読み取りコードを生成する<br/>
/// 読み取るメンバーは、読み取りの単位を型引数に持つ型に対するメンバー参照から決める。値がどのメソッドへ渡っても型が付いて回るので、データフローは追わない
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class JmaXmlGenerator : IIncrementalGenerator
{
	public const string NotSelectedDiagnosticId = "KEVIJMA001";
	public const string InvalidMemberDiagnosticId = "KEVIJMA002";
	public const string UnsupportedViewDiagnosticId = "KEVIJMA003";

	private static readonly DiagnosticDescriptor NotSelectedRule = new(
		NotSelectedDiagnosticId,
		"読み取りの単位の対象に含まれないメンバーの参照",
		"{0} は、{2} で生成された読み取りの単位 {1} の対象に含まれていません。参照すると実行時に例外になります。このアセンブリで別の読み取りの単位を宣言して読み取ってください。",
		"JmaXml",
		DiagnosticSeverity.Error,
		isEnabledByDefault: true);

	private static readonly DiagnosticDescriptor InvalidMemberRule = new(
		InvalidMemberDiagnosticId,
		"[JmaXmlType] の型やメンバーの定義の誤り",
		"{0}: {1}",
		"JmaXml",
		DiagnosticSeverity.Error,
		isEnabledByDefault: true);

	private static readonly DiagnosticDescriptor UnsupportedViewRule = new(
		UnsupportedViewDiagnosticId,
		"読み取りコードを生成できない読み取りの単位",
		"読み取りの単位 {0} の読み取りコードを生成できません: {1}",
		"JmaXml",
		DiagnosticSeverity.Error,
		isEnabledByDefault: true);

	internal static readonly SymbolDisplayFormat TypeFormat = SymbolDisplayFormat.FullyQualifiedFormat
		.AddMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

	/// <summary>
	/// コンパイルごとの型の一覧。メンバー参照 1 件ごとの判定と、読み取りコードの生成の両方から使う
	/// </summary>
	private static readonly ConditionalWeakTable<Compilation, TypeSet> LibraryCache = new();

	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		// 型を定義しているアセンブリ: メンバーの実装と、利用側が型を見つけるための目印を生成する
		var sourceTypes = context.SyntaxProvider.ForAttributeWithMetadataName(
			JmaXmlNames.TypeAttribute,
			static (node, _) => node is ClassDeclarationSyntax,
			static (c, _) => TypeModel.Create((INamedTypeSymbol)c.TargetSymbol));
		context.RegisterSourceOutput(sourceTypes, static (spc, type) =>
		{
			if (type.Error != null)
				spc.ReportDiagnostic(Diagnostic.Create(InvalidMemberRule, Location.None, type.Name, type.Error));
			foreach (var p in type.Props)
			{
				if (p.Error != null)
					spc.ReportDiagnostic(Diagnostic.Create(InvalidMemberRule, p.GetLocation(), type.Name + "." + p.Name, p.Error));
			}
			if (type.Error == null)
				spc.AddSource(type.Key + ".g.cs", JmaXmlTypeEmitter.Emit(type));
		});
		context.RegisterSourceOutput(sourceTypes.Collect(), static (spc, all) =>
		{
			if (all.Length > 0)
				spc.AddSource("JmaXmlTypeLibrary.g.cs", "// <auto-generated/>\n[assembly: global::" + JmaXmlNames.LibraryAttribute.Substring(0, JmaXmlNames.LibraryAttribute.Length - "Attribute".Length) + "]\n");
		});

		var typeSet = context.CompilationProvider.Select(static (compilation, ct) => GetLibrary(compilation, ct));

		var views = context.SyntaxProvider.ForAttributeWithMetadataName(
			JmaXmlNames.ViewAttribute,
			static (node, _) => node is StructDeclarationSyntax,
			static (c, _) => new ViewModel(
				c.TargetSymbol.ContainingNamespace.IsGlobalNamespace ? "" : c.TargetSymbol.ContainingNamespace.ToDisplayString(),
				c.TargetSymbol.Name,
				c.TargetSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
				c.TargetSymbol.ContainingType == null && c.TargetNode is StructDeclarationSyntax { TypeParameterList: null }));

		var usages = context.SyntaxProvider.CreateSyntaxProvider(
				static (node, _) => node is MemberAccessExpressionSyntax or MemberBindingExpressionSyntax or SubpatternSyntax || IsPatternPathHead(node),
				static (c, ct) => FindUsage(c, ct))
			.Where(static u => u != null)
			.Collect()
			.Select(static (all, _) => string.Join("\n", all.Distinct().OrderBy(static u => u, StringComparer.Ordinal)));

		context.RegisterSourceOutput(views.Combine(typeSet).Combine(usages), static (spc, input) =>
		{
			var ((view, typeSet), usages) = input;
			if (!view.IsSupported)
			{
				spc.ReportDiagnostic(Diagnostic.Create(UnsupportedViewRule, Location.None, view.Name, "読み取りの単位は、型引数を持たない名前空間直下の partial 構造体にしてください"));
				return;
			}

			var selected = new HashSet<string>(StringComparer.Ordinal);
			foreach (var usage in usages.Split(['\n'], StringSplitOptions.RemoveEmptyEntries))
			{
				var parts = usage.Split('|');
				// 型引数が型パラメーターのまま参照されたメンバーは、どの読み取りの単位からも使われうる
				if (parts[0] == "U" && (parts[1] == "*" || parts[1] == view.FullName))
					selected.Add(parts[2] + "|" + parts[3]);
			}
			var emitter = new JmaXmlReaderEmitter(view, typeSet, selected);
			var source = emitter.Emit();
			if (emitter.Errors.Count > 0)
			{
				spc.ReportDiagnostic(Diagnostic.Create(UnsupportedViewRule, Location.None, view.Name,
					"次の要素や型に対するメンバーの組み合わせには対応していません: " + string.Join(", ", emitter.Errors.Distinct())));
				return;
			}
			spc.AddSource("JmaXmlView." + (view.Namespace.Length > 0 ? view.Namespace + "." : "") + view.Name + ".g.cs", source);
		});

		context.RegisterSourceOutput(usages, static (spc, usages) =>
		{
			foreach (var usage in usages.Split(['\n'], StringSplitOptions.RemoveEmptyEntries))
			{
				var parts = usage.Split('|');
				if (parts[0] != "D")
					continue;
				var location = Location.Create(
					parts[4],
					new TextSpan(int.Parse(parts[5]), int.Parse(parts[6])),
					new LinePositionSpan(new LinePosition(int.Parse(parts[7]), int.Parse(parts[8])), new LinePosition(int.Parse(parts[9]), int.Parse(parts[10]))));
				spc.ReportDiagnostic(Diagnostic.Create(NotSelectedRule, location, parts[2], parts[1], parts[3]));
			}
		});
	}

	/// <summary>
	/// このコンパイルから見える [JmaXmlType] の型を集める。型は、属性を定義しているアセンブリ自身か、目印の付いた参照先のアセンブリにあるものを対象にする
	/// </summary>
	private static TypeSet GetLibrary(Compilation compilation, CancellationToken cancellationToken)
	{
		if (LibraryCache.TryGetValue(compilation, out var cached))
			return cached;

		var result = TypeSet.Empty;
		if (compilation.GetTypeByMetadataName(JmaXmlNames.TypeAttribute) is { } attributeType)
		{
			var types = new List<TypeModel>();
			if (SymbolEqualityComparer.Default.Equals(attributeType.ContainingAssembly, compilation.Assembly))
				Collect(compilation.Assembly.GlobalNamespace, types, cancellationToken);
			foreach (var assembly in compilation.SourceModule.ReferencedAssemblySymbols)
			{
				if (JmaXmlNames.HasAttribute(assembly, JmaXmlNames.LibraryAttribute))
					Collect(assembly.GlobalNamespace, types, cancellationToken);
			}
			result = new TypeSet(types);
		}
		return LibraryCache.GetValue(compilation, _ => result);

		static void Collect(INamespaceSymbol ns, List<TypeModel> types, CancellationToken cancellationToken)
		{
			cancellationToken.ThrowIfCancellationRequested();
			foreach (var type in ns.GetTypeMembers())
			{
				if (JmaXmlNames.HasAttribute(type, JmaXmlNames.TypeAttribute))
					types.Add(TypeModel.Create(type));
			}
			foreach (var child in ns.GetNamespaceMembers())
				Collect(child, types, cancellationToken);
		}
	}

	/// <summary>
	/// プロパティパターンの <c>{ A.B: ... }</c> の先頭の名前 (A) か。A は左辺を持たないので、メンバーアクセスとしては現れない
	/// </summary>
	private static bool IsPatternPathHead(SyntaxNode node)
	{
		if (node is not IdentifierNameSyntax { Parent: MemberAccessExpressionSyntax access } identifier || access.Expression != identifier)
			return false;
		SyntaxNode top = access;
		while (top.Parent is MemberAccessExpressionSyntax parent)
			top = parent;
		return top.Parent is ExpressionColonSyntax;
	}

	private static string? FindUsage(GeneratorSyntaxContext context, CancellationToken cancellationToken)
	{
		SyntaxNode? nameNode = context.Node switch
		{
			IdentifierNameSyntax identifier => identifier,
			MemberAccessExpressionSyntax access => access.Name,
			MemberBindingExpressionSyntax binding => binding.Name,
			SubpatternSyntax subpattern => (SyntaxNode?)subpattern.NameColon?.Name ?? subpattern.ExpressionColon?.Expression,
			_ => null,
		};
		if (nameNode == null)
			return null;

		// 意味解析は重いので、型のメンバー名と一致しない参照は名前だけで除く
		var library = GetLibrary(context.SemanticModel.Compilation, cancellationToken);
		if (library.Types.Count == 0)
			return null;
		if (nameNode is SimpleNameSyntax simpleName && !library.MemberNames.Contains(simpleName.Identifier.ValueText))
			return null;

		var symbol = context.SemanticModel.GetSymbolInfo(nameNode, cancellationToken).Symbol;
		if (symbol is not (IPropertySymbol or IMethodSymbol))
			return null;
		var containing = symbol.ContainingType;
		if (containing is not { IsGenericType: true } || containing.TypeArguments.Length != 1)
			return null;
		var definition = containing.OriginalDefinition;
		if (!JmaXmlNames.HasAttribute(definition, JmaXmlNames.TypeAttribute) || !JmaXmlNames.HasAttribute(symbol.OriginalDefinition, JmaXmlNames.MemberAttribute))
			return null;

		var argument = containing.TypeArguments[0];
		var key = JmaXmlNames.KeyOf(definition) + "|" + symbol.Name;
		if (argument is ITypeParameterSymbol)
			return "U|*|" + key;
		if (!JmaXmlNames.HasAttribute(argument, JmaXmlNames.ViewAttribute))
			return null;
		if (SymbolEqualityComparer.Default.Equals(argument.ContainingAssembly, context.SemanticModel.Compilation.Assembly))
			return "U|" + argument.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + "|" + key;

		// 別のアセンブリの読み取りの単位: 読み取りコードはそのアセンブリで生成済みで、ここでの参照は反映されない
		foreach (var attribute in argument.GetAttributes())
		{
			if (attribute.AttributeClass?.ToDisplayString() == JmaXmlNames.SelectedAttribute
				&& attribute.ConstructorArguments.Length == 1
				&& attribute.ConstructorArguments[0].Value is string members
				&& (";" + members + ";").Contains(";" + key + ";"))
				return null;
		}
		var location = nameNode.GetLocation();
		var line = location.GetLineSpan();
		return string.Join("|",
			"D", argument.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat), definition.Name + "." + symbol.Name, argument.ContainingAssembly?.Name,
			line.Path, location.SourceSpan.Start, location.SourceSpan.Length,
			line.StartLinePosition.Line, line.StartLinePosition.Character, line.EndLinePosition.Line, line.EndLinePosition.Character);
	}
}
